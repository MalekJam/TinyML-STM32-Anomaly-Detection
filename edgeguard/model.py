"""Small NumPy autoencoder, 12 -> 8 tanh -> 12 linear, MSE reconstruction.
No neural network runtime is needed on the STM32; header exports weights.
"""
from __future__ import annotations
import numpy as np

HIDDEN = 8
SCALE_FLOOR = np.array([0.03]*3 + [1.0]*3 + [0.01]*3 + [0.2]*3, dtype=np.float32)


def fit(train, epochs=240, seed=43):
    train = np.asarray(train, dtype=np.float32)
    if train.ndim != 2 or train.shape[1] != 12:
        raise ValueError("Expected shape (windows, 12)")
    if len(train) < 24:
        raise ValueError("Need at least 24 training windows; capture more normal data")
    rng = np.random.default_rng(seed)
    mean = train.mean(axis=0)
    scale = np.maximum(train.std(axis=0), SCALE_FLOOR)
    z = ((train - mean) / scale).astype(np.float32)
    w1 = (rng.normal(0, 0.15, (12, HIDDEN))).astype(np.float32)
    b1 = np.zeros(HIDDEN, dtype=np.float32)
    w2 = (rng.normal(0, 0.15, (HIDDEN, 12))).astype(np.float32)
    b2 = np.zeros(12, dtype=np.float32)
    pars = [w1,b1,w2,b2]
    m = [np.zeros_like(p) for p in pars]
    v = [np.zeros_like(p) for p in pars]
    for epoch in range(1, int(epochs)+1):
        h = np.tanh(z @ w1 + b1)
        pred = h @ w2 + b2
        dy = (2.0 / (z.shape[0]*12)) * (pred-z)
        dw2 = h.T @ dy
        db2 = dy.sum(axis=0)
        dh = (dy @ w2.T) * (1.0 - h*h)
        dw1 = z.T @ dh
        db1 = dh.sum(axis=0)
        grads = [dw1,db1,dw2,db2]
        for p, gp, mi, vi in zip(pars,grads,m,v):
            np.clip(gp, -20.0,20.0,out=gp)
            mi *= 0.9; mi += 0.1*gp
            vi *= 0.999; vi += 0.001*(gp*gp)
            p -= (0.012 * (mi / (1-0.9**epoch)) /
                  (np.sqrt(vi/(1-0.999**epoch)) + 1e-8))
    return {"mean":mean, "scale":scale, "w1":w1,"b1":b1,"w2":w2,"b2":b2}


def scores(model, features):
    z = (np.asarray(features,dtype=np.float32)-model["mean"])/model["scale"]
    hidden = np.tanh(z @ model["w1"] + model["b1"])
    reconstructed = hidden @ model["w2"] + model["b2"]
    return ((z - reconstructed)**2).mean(axis=-1)


def make_header(model, threshold):
    def arr1(name, a):
        return f"static const float {name}[{len(a)}] = {{"+", ".join(f"{float(x):.9g}f" for x in a)+"};\n"
    def arr2(name, a):
        rows = ["    {"+", ".join(f"{float(x):.9g}f" for x in row)+"}" for row in a]
        return f"static const float {name}[{a.shape[0]}][{a.shape[1]}] = {{\n"+",\n".join(rows)+"\n};\n"
    # Use C literals with decimal point even for integer-valued floats ("1f" invalid).
    def clean_float_suffix(s):
        import re
        return re.sub(r'(?<![\w.])(-?\d+)f(?![\w])',r'\1.0f',s)
    h = ("#ifndef EDGEGUARD_MODEL_GENERATED_H\n#define EDGEGUARD_MODEL_GENERATED_H\n"
         "/* Generated by tools/train_model.py from local sensor captures. */\n"
         "#define EDGEGUARD_MODEL_READY 1\n#define EDGEGUARD_HIDDEN 8\n"
         f"static const float edgeguard_threshold_value = {float(threshold):.9g}f;\n")
    h += arr1("edgeguard_normal_mean", model["mean"])
    h += arr1("edgeguard_normal_scale", model["scale"])
    h += arr2("edgeguard_w1", model["w1"])
    h += arr1("edgeguard_b1", model["b1"])
    h += arr2("edgeguard_w2", model["w2"])
    h += arr1("edgeguard_b2", model["b2"])
    return clean_float_suffix(h+"#endif\n")
